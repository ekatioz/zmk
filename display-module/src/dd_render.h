/*
 * Pure, LVGL-free renderer for the designer-generated status screen.
 *
 * The same drawing code exists in JavaScript (display-designer/lib/render.js); the two
 * are compared pixel by pixel by display-designer/test/run.mjs. Keep them in sync.
 *
 * SPDX-License-Identifier: MIT
 */

#pragma once

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#define DD_W 68
#define DD_H 160
#define DD_WPM_HIST 24

enum dd_kind {
    DD_KIND_NONE,
    DD_KIND_BATTERY,
    DD_KIND_CONNECTION,
    DD_KIND_PROFILE,
    DD_KIND_LAYER,
    DD_KIND_WPM,
    DD_KIND_TEXT,
    DD_KIND_IMAGE,
    DD_KIND_ANIM,
    DD_KIND_CLOCK,
    DD_KIND_DATE,
    DD_KIND_ANALOG,
    DD_KIND_WORDCLOCK,
    DD_KIND_BINARY,
    DD_KIND_MOON,
    DD_KIND_SUN,
};

enum dd_transport {
    DD_TRANSPORT_NONE,
    DD_TRANSPORT_USB,
    DD_TRANSPORT_BLE,
};

/* 1-bit bitmap, rows padded to whole bytes, MSB = leftmost pixel. */
struct dd_bitmap {
    uint8_t w;
    uint8_t h;
    const uint8_t *bits;
};

struct dd_slot {
    uint8_t x, y, w, h;
    uint8_t kind;
    uint8_t scale; /* 0 = automatic */
    uint8_t style;
    uint8_t align; /* 0 center, 1 left, 2 right */
    uint8_t invert;
    uint8_t source;      /* battery: 0 = this half, 1 = other half */
    uint8_t frame_count; /* anim */
    uint8_t frame_div;   /* anim: ticks per frame */
    const char *text;
    const struct dd_bitmap *bitmaps; /* image: 1 entry, anim: frame_count entries */
};

struct dd_layout {
    bool peripheral;
    bool invert;
    uint8_t slot_count;
    uint16_t anim_tick_ms; /* 0 = no animation */
    bool rssi;             /* a widget shows signal strength / the other half's link */
    uint8_t time_mode;     /* redraw because of the time: 0 never, 1 every minute, 2 every second */
    int32_t lat_e4, lon_e4; /* location for the sun times, degrees * 10000 */
    const struct dd_slot *slots;
};

struct dd_state {
    uint8_t battery;
    bool charging;
    int16_t peer_battery; /* < 0: unknown */
    uint8_t transport;
    uint8_t profile; /* 0-based */
    bool profile_connected;
    bool profile_bonded;
    bool link_connected; /* peripheral: link to the central */
    int8_t rssi_link;    /* dBm, 0 = unknown. peripheral: to the central, central: other half */
    int8_t rssi_host;    /* dBm, 0 = unknown. central: to the host */
    uint8_t layer_index;
    const char *layer_label;
    uint8_t wpm[DD_WPM_HIST]; /* oldest first */
    uint32_t utc;             /* seconds since 1970 */
    int16_t utc_offset_min;   /* local time minus UTC */
};

/* Assets, generated by the designer (src/generated/dd_assets.c). */
extern const uint8_t dd_font8[96][8];
extern const struct dd_bitmap dd_icon_bluetooth;
extern const struct dd_bitmap dd_icon_usb;
extern const struct dd_bitmap dd_icon_bolt;
extern const struct dd_bitmap dd_icon_sunrise;
extern const struct dd_bitmap dd_icon_sunset;
extern const int16_t dd_sin720[720]; /* sin(2*pi*i/720) * 1000 */

/* Renders the whole screen into fb (DD_W * DD_H bytes, 1 = ink). */
void dd_render(const struct dd_layout *layout, const struct dd_state *state, uint32_t tick,
               uint8_t *fb);

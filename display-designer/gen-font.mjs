#!/usr/bin/env node
// Extracts the Unscii-8 glyph bitmaps (public domain, by Viznut) from the LVGL source tree
// into lib/font8.js (8 row bytes per glyph, U+0020..U+007F, bit 7 = leftmost pixel).
// Only needed once; the result is committed.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const src =
  process.argv[2] ??
  join(here, "../modules/lib/gui/lvgl/src/font/lv_font_unscii_8.c");
const text = readFileSync(src, "utf8");

const bmpBlock = text.match(/glyph_bitmap\[\] = \{([\s\S]*?)\n\};/)[1];
const bytes = [
  ...bmpBlock.replace(/\/\*[\s\S]*?\*\//g, "").matchAll(/0x([0-9a-fA-F]+)/g),
].map((m) => parseInt(m[1], 16));

const dscBlock = text.match(/glyph_dsc\[\] = \{([\s\S]*?)\n\};/)[1];
const dscs = [
  ...dscBlock.matchAll(
    /\.bitmap_index = (\d+), \.adv_w = (\d+), \.box_w = (\d+), \.box_h = (\d+), \.ofs_x = (-?\d+), \.ofs_y = (-?\d+)/g,
  ),
].map((m) => ({ idx: +m[1], w: +m[3], h: +m[4], ox: +m[5], oy: +m[6] }));

const glyphs = [];
for (let ch = 0x20; ch <= 0x7f; ch++) {
  const d = dscs[ch - 0x20 + 1]; // id 0 is reserved
  const rows = new Array(8).fill(0);
  if (ch !== 0x20) {
    for (let y = 0; y < d.h; y++) {
      for (let x = 0; x < d.w; x++) {
        const bit = d.idx * 8 + y * d.w + x;
        if ((bytes[bit >> 3] >> (7 - (bit & 7))) & 1) {
          const row = 8 - (d.oy + d.h) + y; // baseline is the bottom of the 8px cell
          const col = d.ox + x;
          if (row >= 0 && row < 8 && col >= 0 && col < 8)
            rows[row] |= 0x80 >> col;
        }
      }
    }
  }
  glyphs.push(rows);
}

const out = `// Generated by gen-font.mjs from LVGL's lv_font_unscii_8.c (Unscii by Viznut, public domain).
// 96 glyphs (U+0020..U+007F), 8 rows each, bit 7 = leftmost pixel, cell is 8x8.
export const FONT8 = ${JSON.stringify(glyphs)};
`;
writeFileSync(join(here, "lib/font8.js"), out);
console.log(`wrote lib/font8.js (${glyphs.length} glyphs)`);

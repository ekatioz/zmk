// Turns a design (layout.json) into the C sources of the firmware module (display-module).

import { FONT8 } from "./font8.js";
import { ICONS } from "./icons.js";
import { SIN720 } from "./timecalc.js";
import {
  KINDS,
  STAT_METRICS,
  DEFAULT_LOCATION,
  timeMode,
  ALIGNS,
  computeSlots,
  animTiming,
  widgetAvailable,
} from "./render.js";

const HEADER = `/* Generated by display-designer - do not edit, change the design and regenerate. */\n/* clang-format off */\n\n`;

function hex(b) {
  return "0x" + b.toString(16).padStart(2, "0");
}

function bytesToC(bits) {
  const lines = [];
  for (let i = 0; i < bits.length; i += 12) {
    lines.push(
      "    " +
        bits
          .slice(i, i + 12)
          .map(hex)
          .join(", ") +
        ",",
    );
  }
  return lines.join("\n");
}

function cString(s) {
  let out = '"';
  for (const ch of String(s)) {
    const c = ch.charCodeAt(0);
    if (ch === '"' || ch === "\\") out += "\\" + ch;
    else if (c >= 32 && c < 127) out += ch;
    else out += "?"; // the font only has ASCII
  }
  return out + '"';
}

export function genAssets() {
  let out = HEADER;
  out += '#include "../dd_render.h"\n\n';
  out += "const uint8_t dd_font8[96][8] = {\n";
  FONT8.forEach((rows, i) => {
    out += `    {${rows.map(hex).join(", ")}}, /* U+${(0x20 + i).toString(16).toUpperCase().padStart(4, "0")} */\n`;
  });
  out += "};\n\n";
  out += "const int16_t dd_sin720[720] = {\n";
  for (let i = 0; i < SIN720.length; i += 12)
    out += "    " + SIN720.slice(i, i + 12).join(", ") + ",\n";
  out += "};\n\n";
  for (const [name, ic] of Object.entries(ICONS)) {
    out += `static const uint8_t icon_${name}_bits[] = {\n${bytesToC(ic.bits)}\n};\n`;
    out += `const struct dd_bitmap dd_icon_${name} = {${ic.w}, ${ic.h}, icon_${name}_bits};\n\n`;
  }
  return out;
}

function checkBitmap(bmp, where, maxW, maxH) {
  if (
    !bmp ||
    !Number.isInteger(bmp.w) ||
    !Number.isInteger(bmp.h) ||
    !Array.isArray(bmp.bits)
  ) {
    throw new Error(`${where}: invalid bitmap`);
  }
  if (bmp.w < 1 || bmp.h < 1 || bmp.w > 255 || bmp.h > 255)
    throw new Error(`${where}: bad size`);
  if (bmp.bits.length !== ((bmp.w + 7) >> 3) * bmp.h)
    throw new Error(`${where}: bad data length`);
}

// side: "central" | "peripheral"; design: the whole layout.json object.
export function genLayout(sideName, design) {
  const side = design.sides[sideName];
  const slots = computeSlots(side);
  const timing = animTiming(side);

  let data = "";
  let table = "";
  slots.forEach((slot, idx) => {
    const cfg = side.slots[slot.id] ?? { type: "none" };
    const type = cfg.type || "none";
    if (!KINDS.includes(type))
      throw new Error(`${sideName}/${slot.id}: unknown widget "${type}"`);
    if (!widgetAvailable(type, sideName, cfg)) {
      throw new Error(
        `${sideName}/${slot.id}: widget "${type}" is not available on the ${sideName} half`,
      );
    }
    let bitmapsRef = "NULL";
    let frameCount = 0;
    let frameDiv = 0;
    let textRef = "NULL";
    if (type === "image") {
      if (cfg.bitmap) {
        checkBitmap(cfg.bitmap, `${sideName}/${slot.id}`);
        data += `static const uint8_t bits_${idx}[] = {\n${bytesToC(cfg.bitmap.bits)}\n};\n`;
        data += `static const struct dd_bitmap bmps_${idx}[] = {{${cfg.bitmap.w}, ${cfg.bitmap.h}, bits_${idx}}};\n\n`;
        bitmapsRef = `bmps_${idx}`;
      }
    } else if (type === "anim") {
      const frames = cfg.frames ?? [];
      if (frames.length > 64)
        throw new Error(`${sideName}/${slot.id}: too many frames`);
      if (frames.length) {
        frames.forEach((f, i) => {
          checkBitmap(f, `${sideName}/${slot.id}/frame ${i}`);
          data += `static const uint8_t bits_${idx}_${i}[] = {\n${bytesToC(f.bits)}\n};\n`;
        });
        data += `static const struct dd_bitmap bmps_${idx}[] = {\n`;
        frames.forEach(
          (f, i) => (data += `    {${f.w}, ${f.h}, bits_${idx}_${i}},\n`),
        );
        data += "};\n\n";
        bitmapsRef = `bmps_${idx}`;
        frameCount = frames.length;
        frameDiv = Math.max(
          1,
          Math.round((cfg.period || 1000) / timing.tickMs),
        );
      }
    } else if (type === "text") {
      textRef = cString(cfg.text || "");
    }
    const kind = "DD_KIND_" + type.toUpperCase();
    const align = Math.max(0, ALIGNS.indexOf(cfg.align || "center"));
    const source =
      type === "stat"
        ? Math.max(0, STAT_METRICS.indexOf(cfg.metric))
        : cfg.source === "peer"
          ? 1
          : 0;
    table +=
      `    {.x = ${slot.x}, .y = ${slot.y}, .w = ${slot.w}, .h = ${slot.h}, .kind = ${kind}, ` +
      `.scale = ${cfg.scale | 0}, .style = ${cfg.style | 0}, .align = ${align}, ` +
      `.invert = ${cfg.invert ? 1 : 0}, .source = ${source}, .frame_count = ${frameCount}, ` +
      `.frame_div = ${frameDiv}, .text = ${textRef}, .bitmaps = ${bitmapsRef}}, /* ${slot.id} */\n`;
  });

  const rssi = slots.some((slot) => {
    const cfg = side.slots[slot.id];
    return (
      cfg?.type === "connection" &&
      ((cfg.style | 0) >= 2 ||
        (sideName === "central" && cfg.source === "peer"))
    );
  });

  let out = HEADER;
  out += '#include "../dd_render.h"\n\n';
  out += data;
  out += "static const struct dd_slot slots[] = {\n" + table + "};\n\n";
  out += `const struct dd_layout dd_layout = {\n`;
  out += `    .peripheral = ${sideName === "peripheral" ? "true" : "false"},\n`;
  out += `    .invert = ${design.invert ? "true" : "false"},\n`;
  out += `    .slot_count = ${slots.length},\n`;
  out += `    .anim_tick_ms = ${timing.tickMs},\n`;
  out += `    .rssi = ${rssi ? "true" : "false"},\n`;
  const loc = design.location ?? DEFAULT_LOCATION;
  out += `    .time_mode = ${timeMode(side)},\n`;
  out += `    .lat_e4 = ${Math.round(loc.lat * 1e4)},\n`;
  out += `    .lon_e4 = ${Math.round(loc.lon * 1e4)},\n`;
  out += `    .slots = slots,\n};\n`;
  return out;
}

// All generated files, name -> content.
export function genAll(design) {
  return {
    "dd_assets.c": genAssets(),
    "dd_layout_central.c": genLayout("central", design),
    "dd_layout_peripheral.c": genLayout("peripheral", design),
  };
}
